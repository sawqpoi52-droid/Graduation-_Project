export const translateBreaches = (breaches, lang = 'ar') => {
    if (!breaches || !Array.isArray(breaches) || lang !== 'ar') return breaches;

    return breaches.map(breach => {
        const translation = BREACH_TRANSLATIONS[breach.Name] || BREACH_TRANSLATIONS[breach.Title];
        if (translation) {
            return { ...breach, Title: translation.Title, Description: translation.Description };
        }

        const date = new Date(breach.BreachDate).toLocaleDateString('ar-EG');
        const translatedClasses = (breach.DataClasses || []).map(dc => DATA_CLASS_TRANSLATIONS[dc] || dc);
        return {
            ...breach,
            Description: `في تاريخ ${date}، تعرض موقع ${breach.Title} لحادثة تسريب بيانات. البيانات التي تم كشفها تتضمن: ${translatedClasses.join('، ')}.`
        };
    });
};

